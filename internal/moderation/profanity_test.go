package moderation

import "testing"

func TestObscene(t *testing.T) {
	bad := []string{
		"Бля, опять не получается", "это просто пиздец", "Х*У*Й знает", "xyйня какая-то", "б л я", "бляяяять",
		"заебись", "выебываешься", "долбоёб", "ёб твою", "ебать", "наебал", "съебался", "мудак", "пидор",
		"сука", "сучка", "п1зд", "пuздец", "hui", "blyat", "гандон", "шлюха", "дрочит", "ахуеть", "нихуя", "уебки",
	}
	ok := []string{
		"На 1:20 поворот через левое плечо", "Спасибо, очень помогло!", "Чёрт, опять сбилась", "себе", "себя",
		"вебинар", "небо", "перебить", "употреблять", "бляха", "застрахуйте", "мудрый", "педикюр", "хулиган",
		"художник", "сукно", "Хуан", "ребята", "учебный", "хлеба", "грибы", "оскорблять", "употребляют",
		"Hello world", "dance", "погибать", "ошибаться", "сугроб", "ребёнок",
	}
	for _, s := range bad {
		if !Obscene(s) {
			t.Errorf("missed: %q", s)
		}
	}
	for _, s := range ok {
		if Obscene(s) {
			t.Errorf("false positive: %q", s)
		}
	}
}
